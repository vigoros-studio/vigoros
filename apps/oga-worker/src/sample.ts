export const samplePack = (places: string[]): ResearchPack => {
  const found: PackPlace[] = []
  const notes: string[] = [
    'SAMPLE MODE: values copied from OneGoodArea’s 12 October 2026 re-run of two postcodes (methodology 1.12.5). No live call was made.',
  ]
  for (const p of places) {
    const key = p.trim().toUpperCase().replace(/\s+/g, ' ')
    const hit = SAMPLE_PLACES[key]
    if (hit) found.push(hit)
    else
      notes.push(
        `${p}: not in the sample pack (only SE15 5DP and LA22 0EN are); nothing invented for it.`,
      )
  }
  return {
    mode: 'sample',
    fetchedAt: new Date().toISOString(),
    apiBase: 'sample://docs/oga/OneGoodArea-Infabode-sample-postcodes-2026-10.md',
    methodologyVersion: V,
    places: found,
    sources: [
      'police.uk',
      'ONS Census 2021',
      'IMD 2025',
      'ONS HPSSA',
      'HM Land Registry',
      'Ofsted',
      'OpenStreetMap',
      'NaPTAN',
      'Environment Agency',
    ],
    notes,
  }
}

